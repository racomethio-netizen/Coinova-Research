import { Badge, Notice } from "@/components/ui";
import { siteConfig } from "@/config/site";
import { fmtDecimal } from "@/lib/format";

/** Direction badge: text + colour (never colour alone). */
export function DirectionBadge({ direction }: { direction: "BUY" | "SELL" }) {
  return <Badge tone={direction === "BUY" ? "positive" : "negative"}>{direction === "BUY" ? "▲ BUY" : "▼ SELL"}</Badge>;
}

const OUTCOME_LABEL: Record<string, { label: string; tone: "positive" | "negative" | "neutral" | "warning" }> = {
  win: { label: "Target hit", tone: "positive" },
  loss: { label: "Stopped out", tone: "negative" },
  expired_closed: { label: "Closed at horizon", tone: "neutral" },
  expired_no_entry: { label: "Expired, no entry", tone: "neutral" },
  invalidated: { label: "Invalidated", tone: "warning" },
};

export function OutcomeBadge({ outcome }: { outcome: string | null }) {
  if (!outcome) return <Badge tone="accent">Open</Badge>;
  const o = OUTCOME_LABEL[outcome] ?? { label: outcome, tone: "neutral" as const };
  return <Badge tone={o.tone}>{o.label}</Badge>;
}

export function Price({ v }: { v: string | number | null | undefined }) {
  return <span className="font-mono tabular-nums">{v === null || v === undefined ? "—" : fmtDecimal(String(v), 8)}</span>;
}

export function RiskDisclosure() {
  return (
    <p className="mt-8 text-xs leading-relaxed text-faint">
      Research and paper trading only. Not financial advice. Signals are generated by a rules-based model whose confidence is not
      calibrated; past results, including backtests, do not indicate future results. Crypto assets are volatile and you can lose money.{" "}
      {siteConfig.disclaimer}
    </p>
  );
}

export function NotConfigured({ what }: { what: string }) {
  return (
    <Notice tone="warning" title={`${what} is not available`}>
      The market-data database is not configured on this server. Nothing is shown rather than placeholder data.
    </Notice>
  );
}
